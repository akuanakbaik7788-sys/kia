-- Run this SQL in Supabase Dashboard > SQL Editor.
-- This creates public release listings and an explicit admin allowlist.
-- Never expose your Supabase service_role key in this website.

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.releases (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  description text not null default '' check (char_length(description) <= 500),
  download_url text not null,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;
alter table public.releases enable row level security;

-- Signed-in users can only check their own admin membership.
drop policy if exists "Admins can read own membership" on public.admin_users;
create policy "Admins can read own membership"
on public.admin_users for select to authenticated
using (user_id = (select auth.uid()));

-- Public may view published releases. Only allowlisted admins can modify.
drop policy if exists "Anyone can view releases" on public.releases;
create policy "Anyone can view releases"
on public.releases for select to anon, authenticated
using (true);

drop policy if exists "Admins can insert releases" on public.releases;
create policy "Admins can insert releases"
on public.releases for insert to authenticated
with check (
  created_by = (select auth.uid())
  and exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  )
);

drop policy if exists "Admins can update releases" on public.releases;
create policy "Admins can update releases"
on public.releases for update to authenticated
using (
  exists (select 1 from public.admin_users where user_id = (select auth.uid()))
)
with check (
  exists (select 1 from public.admin_users where user_id = (select auth.uid()))
);

drop policy if exists "Admins can delete releases" on public.releases;
create policy "Admins can delete releases"
on public.releases for delete to authenticated
using (
  exists (select 1 from public.admin_users where user_id = (select auth.uid()))
);

